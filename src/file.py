import os
import sys
import subprocess
from pathlib import Path

# Find project root wether we're running the script as .py or .exe
PROJECT_ROOT = (
    Path(sys.executable).resolve().parent if getattr(sys, "frozen", False) else
    Path(__file__).resolve().parents[1]
)

TEMPOUTPUT_FOLDER = PROJECT_ROOT / ".tmp"
OUTPUT_FOLDER = PROJECT_ROOT / "outputImage"
VERSION_FILE = PROJECT_ROOT / "VERSION"
CONF_FILE = PROJECT_ROOT / "configuration.txt"
INPUT_FILE = PROJECT_ROOT / "pokemonData.txt"
SPRITE_FOLDER = PROJECT_ROOT / "sprites"

POKEMONSPRITE_FOLDER = SPRITE_FOLDER / "pokemon"
ITEMSPRITE_FOLDER = SPRITE_FOLDER / "items"
TRAINERSPRITE_FOLDER = SPRITE_FOLDER / "trainers"
BACKGROUNDPRITE_FOLDER = SPRITE_FOLDER / "background"
MISCSPRITE_FOLDER = SPRITE_FOLDER / "misc"

DATAFILE_ENV_VARIABLE_NAME = "PLATINUMKAIZODISPLAY_DATAFILE"

# Create env variable and folders
def ensureSetup():

    # Set path as global env variable for lua script
    subprocess.run(["setx", DATAFILE_ENV_VARIABLE_NAME, str(INPUT_FILE)], check = True, stdout = subprocess.DEVNULL)

    # Create outputImage and .tmp folders, set .tmp as hidden
    OUTPUT_FOLDER.mkdir(exist_ok = True)
    TEMPOUTPUT_FOLDER.mkdir(exist_ok = True)
    subprocess.run(["attrib", "+h", str(TEMPOUTPUT_FOLDER)], check = True)

    # Notify user when ready to use
    print("\nPlatinum Kaizo Display version " + safeReadFile(VERSION_FILE) +  " currently running...")
    print("Make sure PlatinumKaizoDisplay.lua script is also running !\n")


# Read file safely even if used by lua script
def safeReadFile(path):
    try:
        with open(path, "r", encoding="utf-8") as f:
            return f.read().strip()
    except Exception:
        return None


# Write file safely even if used by OBS
def safeWriteFile(image, fileName):

    # Save final image in .tmp folder to avoid OBS reading partially written image
    tempOutputPath = os.path.join(TEMPOUTPUT_FOLDER, f"{fileName.lower()}.png")
    outputPath = os.path.join(OUTPUT_FOLDER, f"{fileName.lower()}.png")
    image.save(tempOutputPath, "PNG")
    image.close()

    # Swap temp image and output image
    try:
        os.replace(tempOutputPath, outputPath)

    # PermissionError errors might occur because OBS is reading the image, don't print those
    except PermissionError:
        pass


# Read configuration.txt and convert user preferences into boolean
def readConfFile():
    configuration = {}
    configurationFile = safeReadFile(CONF_FILE)

    for line in configurationFile.splitlines():
        line = line.replace(" ","") # Remove spaces if any

        if (line.count("=") == 1):
            configurationSplit = line.split("=")
            configuration[configurationSplit[0]] = int(configurationSplit[1]) if configurationSplit[1].isnumeric() else configurationSplit[1]

    return configuration


# Read pokemonData.txt generated by lua script
def readPokemonData():
    return safeReadFile(INPUT_FILE)


# Return pokemon sprite path
def getPokemonSprite(pokedexId):
    pokemonSpritePath = POKEMONSPRITE_FOLDER / f"{pokedexId}.png"

    # No Pokemon found : return default sprite
    if not pokemonSpritePath.exists():
        pokemonSpritePath = POKEMONSPRITE_FOLDER / "0.png"

    return pokemonSpritePath


# Return item sprite path
def getItemSprite(itemId):
    itemSpritePath = ITEMSPRITE_FOLDER / f"{itemId}.png"

    # No item found : return default sprite
    if not itemSpritePath.exists():
        itemSpritePath = ITEMSPRITE_FOLDER / "0.png"

    return itemSpritePath